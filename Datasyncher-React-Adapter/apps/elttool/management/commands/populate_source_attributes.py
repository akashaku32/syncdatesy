class Command(BaseCommand):
    help = 'Populate SourceAttribute instances from source attributes'

    def add_arguments(self, parser):
        parser.add_argument(
            '--clear-existing',
            action='store_true',
            help='Clear existing SourceAttribute data before populating new data',
        )
        parser.add_argument(
            '--source',
            type=str,
            help='Clear and populate data for a specific source only (e.g., Snowflake, SFTP)',
        )
        parser.add_argument(
            '--reorder',
            action='store_true',
            help='Reorder attributes by updating `src_attr_id` to match `sources_data` order (uses attribute_name).',
        )

    def handle(self, *args, **options):
        clear_existing = options.get('clear_existing', False)
        specific_source = options.get('source')
        reorder = options.get('reorder', False)
        
        if clear_existing:
            if specific_source:
                # Clear data for specific source
                self.clear_source_attributes(specific_source)
            else:
                # Clear all source attributes
                self.clear_all_source_attributes()
        
        # Filter sources if specific source is requested
        sources_to_process = sources_data
        if specific_source:
            sources_to_process = [s for s in sources_data if s["name"] == specific_source]
            if not sources_to_process:
                self.stdout.write(
                    self.style.ERROR(f'Source "{specific_source}" not found in sources_data')
                )
                return
        
        for source_data in sources_to_process:
            source_name = source_data["name"]
            
            # Check if source already exists
            source_model_instance, created = SourceModel.objects.get_or_create(
                name=source_name,
                defaults={
                    'src_id': (
                        (SourceModel.objects.aggregate(m=Max('src_id')).get('m') or 0) + 1
                    ),
                    'dst_schema': source_data.get('dst_schema', ''),
                    'deflt_interval': source_data.get('deflt_interval', '15'),
                    'is_rtl': source_data.get('is_rtl', False),
                    'display_name': source_data.get('display_name'),
                    'disable_update_schema': source_data.get('disable_update_schema', False),
                }
            )
            
            if created:
                self.stdout.write(
                    self.style.SUCCESS(f'Created new source: {source_name}')
                )
            else:
                desired_model_fields = {
                    'dst_schema': source_data.get('dst_schema', ''),
                    'deflt_interval': source_data.get('deflt_interval', '15'),
                    'is_rtl': source_data.get('is_rtl', False),
                    'display_name': source_data.get('display_name'),
                    'disable_update_schema': source_data.get('disable_update_schema', False),
                }
                changed_fields = []
                for field, value in desired_model_fields.items():
                    if hasattr(source_model_instance, field) and getattr(source_model_instance, field) != value:
                        setattr(source_model_instance, field, value)
                        changed_fields.append(field)
                if changed_fields:
                    source_model_instance.save(update_fields=changed_fields)

                self.stdout.write(
                    self.style.WARNING(f'Source already exists: {source_name}. Checking for missing attributes...')
                )
            
            # Track attributes that were added
            added_attributes = []
            updated_attributes = []
            skipped_attributes = []

            if source_name == "AzureDataLakeStorage":
                SourceAttribute.objects.filter(
                    src=source_model_instance,
                    attribute_name__in=["root_folder", "base_folder_path", "folder_path", "adls_base_prefix"],
                ).delete()
            
            for attribute_data in source_data["attributes"]:
                attribute_name = attribute_data["attribute_name"]
                
                # Check if this attribute already exists for this source
                existing_attribute = SourceAttribute.objects.filter(
                    src=source_model_instance,
                    attribute_name=attribute_name
                ).first()
                
                if existing_attribute:
                    updated = self._sync_existing_attribute(existing_attribute, attribute_data)
                    if updated:
                        updated_attributes.append(attribute_name)
                        self.stdout.write(f'  🔁 Updated existing attribute: {attribute_name}')
                    else:
                        skipped_attributes.append(attribute_name)
                        self.stdout.write(f'  ⏭️  Skipped existing attribute: {attribute_name} (no changes)')
                    continue
                
                # Create the new attribute
                attribute_kwargs = {
                    'src': source_model_instance,
                    'attribute_name': attribute_data["attribute_name"],
                    'input_type': attribute_data["input_type"],
                    'label': attribute_data["label"],
                    'required': attribute_data.get("required", True),
                    'is_visible': attribute_data.get("is_visible", True),
                    'read_only': attribute_data.get("read_only", False),
                    'depend_on': attribute_data.get("depend_on"),
                    # Support both "dependency" (legacy) and "dependency_value" (new format)
                    'dependency_value': attribute_data.get("dependency_value") or attribute_data.get("dependency"),
                }

                if "widget" in attribute_data:
                    attribute_kwargs['widget'] = attribute_data["widget"]

                if "choices" in attribute_data:
                    attribute_kwargs['choices'] = attribute_data["choices"]

                if "description" in attribute_data:
                    attribute_kwargs['description'] = attribute_data["description"]

                if "placeholder" in attribute_data:
                    attribute_kwargs['placeholder'] = attribute_data["placeholder"]

                if "default_value" in attribute_data:
                    attribute_kwargs['default_value'] = attribute_data["default_value"]

                SourceAttribute.objects.create(**attribute_kwargs)
                added_attributes.append(attribute_name)
                self.stdout.write(
                    f'  [added] New attribute: {attribute_name}'
                )

            # Summary
            if added_attributes or updated_attributes:
                self.stdout.write(
                    self.style.SUCCESS(
                        f'Successfully synced {source_name}: added={len(added_attributes)}, updated={len(updated_attributes)}'
                    )
                )
            else:
                self.stdout.write(
                    self.style.WARNING(
                        f'No new attributes added to {source_name} - all attributes already exist'
                    )
                )
            
            if skipped_attributes:
                self.stdout.write(
                    f'  Skipped {len(skipped_attributes)} existing attributes: {", ".join(skipped_attributes)}'
                )

        if reorder:
            if specific_source:
                # Best-effort reorder only for the selected source.
                source_model = SourceModel.objects.get(name=specific_source)
                source_data = next((s for s in sources_data if s["name"] == specific_source), None)
                if source_data:
                    self._reorder_attributes_for_source(source_model, source_data)
                    self.stdout.write(self.style.SUCCESS(f'Reordered attributes for {specific_source}.'))
            else:
                # Reorder all sources in src_id ASC, so ordering is stable across the UI.
                self._reorder_all_sources_in_src_id_order()
                self.stdout.write(self.style.SUCCESS('Reordered all source attributes by src_id (ASC).'))

    def clear_all_source_attributes(self):
        """Clear all SourceAttribute instances"""
        count = SourceAttribute.objects.count()
        SourceAttribute.objects.all().delete()
        self.stdout.write(
            self.style.WARNING(f'Cleared {count} SourceAttribute instances')
        )

    def clear_source_attributes(self, source_name):
        """Clear SourceAttribute instances for a specific source"""
        try:
            source_model = SourceModel.objects.get(name=source_name)
            count = SourceAttribute.objects.filter(src=source_model).count()
            SourceAttribute.objects.filter(src=source_model).delete()
            self.stdout.write(
                self.style.WARNING(f'Cleared {count} SourceAttribute instances for {source_name}')
            )
        except SourceModel.DoesNotExist:
            self.stdout.write(
                self.style.ERROR(f'Source "{source_name}" does not exist')
            )

    def _sync_existing_attribute(self, existing_attribute, attribute_data):
        desired = {
            'input_type': attribute_data.get("input_type"),
            'label': attribute_data.get("label"),
            'required': attribute_data.get("required", True),
            'is_visible': attribute_data.get("is_visible", True),
            'read_only': attribute_data.get("read_only", False),
            'widget': attribute_data.get("widget"),
            'choices': attribute_data.get("choices"),
            'depend_on': attribute_data.get("depend_on"),
            'dependency_value': attribute_data.get("dependency_value") or attribute_data.get("dependency"),
            'description': attribute_data.get("description"),
            'placeholder': attribute_data.get("placeholder"),
            'default_value': attribute_data.get("default_value"),
        }

        changed_fields = []
        for field, value in desired.items():
            if hasattr(existing_attribute, field) and getattr(existing_attribute, field) != value:
                setattr(existing_attribute, field, value)
                changed_fields.append(field)

        if changed_fields:
            existing_attribute.save(update_fields=changed_fields)
            return True
        return False

    def _reorder_attributes_for_source(self, source_model_instance, source_data):
        """
        Reorder SourceAttribute rows for a source by updating their primary key `src_attr_id`
        so `.order_by("src_attr_id")` matches the order in `sources_data`.

        Ordering key: attribute_name (must be unique per source).
        Any extra attributes not present in `sources_data` are appended at the end
        in their current `src_attr_id` order.
        """
        desired_names = [a.get('attribute_name') for a in source_data.get('attributes', []) if a.get('attribute_name')]
        desired_set = set(desired_names)

        existing = list(SourceAttribute.objects.filter(src=source_model_instance).order_by('src_attr_id'))
        existing_by_name = {a.attribute_name: a for a in existing}

        ordered = [existing_by_name[name] for name in desired_names if name in existing_by_name]
        leftovers = [a for a in existing if a.attribute_name not in desired_set]
        ordered.extend(leftovers)

        current_order_names = [a.attribute_name for a in existing]
        target_order_names = [a.attribute_name for a in ordered]
        if current_order_names == target_order_names:
            return False

        max_id = SourceAttribute.objects.aggregate(max_id=Max('src_attr_id')).get('max_id') or 0
        base = max_id + 1

        updates = []
        for i, attr in enumerate(ordered):
            new_id = base + i
            if attr.src_attr_id != new_id:
                updates.append((attr.src_attr_id, new_id))

        # Update by old PK to avoid losing references during the loop
        for old_id, new_id in updates:
            SourceAttribute.objects.filter(src_attr_id=old_id).update(src_attr_id=new_id)

        return True

    def _reorder_all_sources_in_src_id_order(self):
        """
        Globally reassign `src_attr_id` so that:
          1) Sources are grouped by SourceModel.src_id ascending
          2) Within each source, attributes follow `sources_data` order (by attribute_name) when present
          3) Any extra attributes not present in `sources_data` are appended (preserving current order)

        This matches UI ordering because the API uses `.order_by("src_attr_id")`.
        """
        # Use the static seed order (QA CSV) when available, otherwise keep existing order.
        source_data_by_name = {s["name"]: s for s in sources_data if s.get("name")}

        models = list(SourceModel.objects.all().order_by("src_id"))

        global_order = []
        for model in models:
            source_data = source_data_by_name.get(model.name, {})
            desired_names = [a.get("attribute_name") for a in source_data.get("attributes", []) if a.get("attribute_name")]
            desired_set = set(desired_names)

            existing = list(SourceAttribute.objects.filter(src=model).order_by("src_attr_id"))
            existing_by_name = {a.attribute_name: a for a in existing}

            ordered = [existing_by_name[name] for name in desired_names if name in existing_by_name]
            leftovers = [a for a in existing if a.attribute_name not in desired_set]
            ordered.extend(leftovers)

            global_order.extend(ordered)

        if not global_order:
            return False

        max_id = SourceAttribute.objects.aggregate(max_id=Max("src_attr_id")).get("max_id") or 0
        temp_base = max_id + 10000

        with transaction.atomic():
            # Phase 1: move everything to a collision-free temp range
            for i, attr in enumerate(global_order):
                SourceAttribute.objects.filter(src_attr_id=attr.src_attr_id).update(src_attr_id=temp_base + i)

            # Phase 2: assign final ids from 1..N in the desired global order
            for i in range(len(global_order)):
                SourceAttribute.objects.filter(src_attr_id=temp_base + i).update(src_attr_id=i + 1)

        return True
